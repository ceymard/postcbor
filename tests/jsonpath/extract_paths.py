"""Collects every single-quoted literal from PostgreSQL's jsonpath regression tests, as candidate paths.

Usage: python3 tests/jsonpath/extract_paths.py <postgres source dir> > postcbor/tests/pg_regress/sql/jsonpath_decode.sql
The literals that do not parse as jsonpath on the running PostgreSQL version are skipped by the suite itself.
"""
import re
import sys

src = sys.argv[1]
lits = []
seen = set()
for name in ("jsonpath.sql", "jsonb_jsonpath.sql"):
    text = open(f"{src}/src/test/regress/sql/{name}", encoding="utf-8").read()
    # Standard SQL strings ('' doubles a quote); E'' strings are rare and skipped.
    for m in re.finditer(r"(?<![A-Za-z0-9_E])'((?:[^']|'')*)'", text):
        lit = m.group(1)
        if lit not in seen and len(lit) < 2000:
            seen.add(lit)
            lits.append(lit)

print("-- Every path literal of PostgreSQL's jsonpath regression tests (generated by tests/jsonpath/extract_paths.py):")
print("-- decoding then printing must give a path that PostgreSQL reads back to the same path. Only mismatches print.")
print("CREATE TEMP TABLE candidates (lit text);")
print("INSERT INTO candidates VALUES")
print(",\n".join("('" + l.replace("'", "''") + "')" for l in lits) + ";")
print("""DO $$
DECLARE r record; p jsonpath; checked int := 0;
BEGIN
    FOR r IN SELECT lit FROM candidates LOOP
        BEGIN
            p := r.lit::jsonpath;
        EXCEPTION WHEN others THEN
            CONTINUE;
        END;
        checked := checked + 1;
        BEGIN
            IF postcbor_jsonpath_print(p)::jsonpath::text <> p::text THEN
                RAISE WARNING 'path % printed as %', p, postcbor_jsonpath_print(p);
            END IF;
        EXCEPTION WHEN others THEN
            RAISE WARNING 'path % printed as % fails: %', p, postcbor_jsonpath_print(p), SQLERRM;
        END;
    END LOOP;
    IF checked < 300 THEN
        RAISE WARNING 'only % paths checked', checked;
    END IF;
END $$;
-- A path read from a table (stored with a short header, not aligned) decodes the same.
CREATE TEMP TABLE stored (p jsonpath);
INSERT INTO stored VALUES ('$.a'), ('strict $.a[1 to 3, last]'), ('$ ? (@.x > 1.50 && @.y like_regex "^a" flag "i")');
SELECT count(*) FROM stored WHERE postcbor_jsonpath_print(p)::jsonpath::text <> p::text;
-- Nesting beyond the decoder's limit is refused cleanly.
SELECT postcbor_jsonpath_print(('$' || repeat('.a', 300))::jsonpath);""")
